#![allow(clippy::print_stdout, clippy::print_stderr)]
//! Writes `noir/lib/channel/src/vectors.nr`: the values the Noir library's
//! tests compare against, computed by the wallet library from label-derived
//! randomness (so the file is reproducible and no secret is in it).
//!
//! cargo run --release -p zk-encryption-circuits --bin vectors [-- --check]

use ark_ff::PrimeField;
use sha3::digest::{ExtendableOutput, Update, XofReader};
use sha3::{Digest, Sha3_256};
use std::fmt::Write as _;
use zk_encryption::Fr;
use zk_encryption::lattice::{Kpke, MlKemKeys, Noise};
use zk_encryption::poseidon::FieldHex;
use zk_encryption::ratchet::{Handshake, Ratchet, ReceiverKeys};

const HEADER: &str =
    "Generated by `vectors` (rust/zk-encryption-circuits/src/bin/vectors.rs); do not edit.";

fn fr(label: &str) -> Fr {
    Fr::from_le_bytes_mod_order(&Sha3_256::digest(label.as_bytes())[..31])
}

fn bytes<const N: usize>(label: &str) -> [u8; N] {
    let mut b = [0u8; N];
    let mut x = sha3::Shake256::default();
    x.update(label.as_bytes());
    x.finalize_xof().read(&mut b);
    b
}

fn list<T>(xs: impl IntoIterator<Item = T>, f: impl Fn(T) -> String) -> String {
    format!("[{}]", xs.into_iter().map(f).collect::<Vec<_>>().join(", "))
}

fn fields(v: &[Fr]) -> String {
    list(v, |x| x.hex())
}

fn signed(p: &[i8; 256]) -> String {
    list(p, |c| Fr::from(i64::from(*c)).hex())
}

fn polys(p: &[[u16; 256]]) -> String {
    list(p, |x| list(x, |c| c.to_string()))
}

/// The channel library's vectors.
pub fn channel_vectors() -> String {
    let keys = MlKemKeys::from_seed(bytes("bob ml-kem seed"));
    let bob = ReceiverKeys::from_secrets(fr("bob grumpkin"), keys);
    let noise = Noise::cbd(&bytes("noise"));
    let m: [u8; 32] = bytes("m");
    let ct = Kpke::encrypt(&bob.public.pq, &noise, &m).expect("encrypt");
    let e = fr("e");
    let hs = Handshake::new(&bob.public, e, &noise, &m).expect("handshake");
    let (s, ctx) = (fr("chain key"), fr("ctx"));
    let pt: Vec<Fr> = (1..=6u64).map(|i| Fr::from(i * 1_000_003)).collect();
    let (c_t, sealed) = Ratchet::seal(Ratchet::key_payload(), s, ctx, &pt).expect("seal");
    let mut o = format!("// {HEADER}\n\n");
    let mut g = |name: &str, ty: &str, val: String| {
        writeln!(o, "pub global {name}: {ty} = {val};").expect("write")
    };
    let pq = &bob.public.pq;
    g(
        "PQ_A_HAT",
        "[[[Field; 256]; 3]; 3]",
        list(pq.a_hat.iter(), |r| polys(r)),
    );
    g("PQ_T_HAT", "[[Field; 256]; 3]", polys(&pq.t_hat));
    g(
        "PQ_H_EK",
        "[u64; 4]",
        list(pq.h_ek_lanes(), |x| x.to_string()),
    );
    g("PQ_COMMITMENT", "Field", pq.commitment().hex());
    g("NOISE_R", "[[Field; 256]; 3]", list(noise.r.iter(), signed));
    g(
        "NOISE_E1",
        "[[Field; 256]; 3]",
        list(noise.e1.iter(), signed),
    );
    g("NOISE_E2", "[Field; 256]", signed(&noise.e2));
    g("M", "[u8; 32]", list(m, |b| b.to_string()));
    g("CT_U", "[[Field; 256]; 3]", polys(&ct.u));
    g("CT_V", "[Field; 256]", list(ct.v, |c| c.to_string()));
    g("CT_COMMITMENT", "Field", ct.commitment().hex());
    g(
        "RECEIVER",
        "[Field; 2]",
        fields(&[bob.public.grumpkin.x, bob.public.grumpkin.y]),
    );
    g("E", "Field", e.hex());
    g(
        "HS_EPHEMERAL",
        "[Field; 2]",
        fields(&[hs.ephemeral.x, hs.ephemeral.y]),
    );
    g("HS_TAG", "Field", hs.tag.hex());
    g("HS_ROOT", "Field", hs.root.hex());
    g("S", "Field", s.hex());
    g("CTX", "Field", ctx.hex());
    g("PLAINTEXT", "[Field; 6]", fields(&pt));
    g("SEALED_COMMITMENT", "Field", c_t.hex());
    g("SEALED_CIPHERTEXT", "[Field; 6]", fields(&sealed));
    // The payload code is generic in the size: a 9-field payload under KEY_NOTE.
    let payload9: [Fr; 9] = std::array::from_fn(|i| fr(&format!("payload 9 {i}")));
    let salt9 = fr("payload 9 salt");
    let (c9, ct9) = Ratchet::seal_payload(Ratchet::key_note(), s, ctx, &payload9).expect("seal");
    let mut env9 = vec![
        Ratchet::payload_commitment(salt9, &payload9),
        ctx,
        c9,
        Ratchet::key_note(),
    ];
    env9.extend(ct9);
    g("PAYLOAD9", "[Field; 9]", fields(&payload9));
    g("PAYLOAD9_SALT", "Field", salt9.hex());
    g("PAYLOAD9_COMMITMENT", "Field", env9[0].hex());
    g("PAYLOAD9_ENVELOPE", "[Field; 13]", fields(&env9));
    g("NEXT", "Field", Ratchet::next(s).hex());
    // The session app: a handshake (C_0 of the transcript root) and a ratchet transfer (C_t of s).
    let ep = &hs.ephemeral;
    g(
        "SESSION_HANDSHAKE",
        "[Field; 6]",
        fields(&[
            ctx,
            Ratchet::commit(hs.root),
            ep.x,
            ep.y,
            hs.tag,
            hs.ct_commitment,
        ]),
    );
    g(
        "SESSION_RATCHET",
        "[Field; 6]",
        fields(&[
            ctx,
            Ratchet::commit(s),
            ep.x,
            ep.y,
            hs.tag,
            hs.ct_commitment,
        ]),
    );
    o
}

fn main() {
    let path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../noir/lib/channel/src/vectors.nr"
    );
    let text = channel_vectors();
    if std::env::args().any(|a| a == "--check") {
        let committed = std::fs::read_to_string(path).unwrap_or_default();
        // Modulo `nargo fmt`'s reflow (whitespace and trailing commas).
        let norm = |s: &str| {
            s.chars()
                .filter(|c| !c.is_whitespace() && *c != ',')
                .collect::<String>()
        };
        if norm(&committed) != norm(&text) {
            eprintln!("stale: {path} (rerun without --check)");
            std::process::exit(1);
        }
        eprintln!("vectors are current");
        return;
    }
    std::fs::write(path, text).expect("write");
    eprintln!("wrote {path}");
}
